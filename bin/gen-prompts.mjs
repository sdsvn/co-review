#!/usr/bin/env node
// Copies the shared agent prompts in prompts/ to every place an agent reads them (see prompts/README.md).
//
//   node bin/gen-prompts.mjs           rewrite the copies (make prompts)
//   node bin/gen-prompts.mjs --check   exit 1 if a copy is out of date (make check-prompts)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

/** Each harness's name for a Co-Review tool. */
const TOOLS = {
    mcp: {
        open_review: 'open_review', await_reviewer: 'await_reviewer', reply: 'reply', add_findings: 'add_findings',
        ask_reviewer: 'ask_reviewer', repo_map: 'repo_map', post_review_to_github: 'post_review_to_github'
    },
    pi: {
        open_review: 'co_review_start', await_reviewer: 'co_review_wait', reply: 'co_review_reply',
        add_findings: 'co_review_add_findings', ask_reviewer: 'co_review_ask',
        repo_map: 'co_review_map', post_review_to_github: 'co_review_post_github'
    }
};

/** The strings the MCP server embeds: the region of this Rust file between the two marker lines. */
const RS_OUT = 'crates/review_mcp/src/prompts.rs';
const RS_BEGIN = '// prompts: generated by `make prompts` from prompts/*.md. Edit those files, not this region.\n';
const RS_END = '// prompts: end of the generated region.\n';

/** A Rust string literal; characters outside ASCII as `\u{…}` escapes. */
function rust(text) {
    return JSON.stringify(text).replace(/[^\x20-\x7e]/gu, c => `\\u{${c.codePointAt(0).toString(16)}}`);
}

function rustRegion() {
    return RS_BEGIN
        + '\n/// A literal, so `SERVER_INSTRUCTIONS` can `concat!` it.\n'
        + `macro_rules! answer_style {\n    () => {\n        ${rust(render('answer-style', 'mcp'))}\n    };\n}\n\n`
        + 'pub const ANSWER_STYLE: &str = answer_style!();\n\n'
        + `pub const ANSWER_STYLE_SHORT: &str = ${rust(render('answer-style-short', 'mcp'))};\n\n`
        + `pub const DESIGN_PROMPT: &str = ${rust(render('design', 'mcp'))};\n\n`;
}

function render(name, harness) {
    const text = readFileSync(join(root, 'prompts', `${name}.md`), 'utf8').trimEnd();
    return text
        .replace(/\{\{>\s*([\w-]+)\s*\}\}/g, (_m, inc) => render(inc, harness))
        .replace(/\{\{(\w+)\}\}/g, (m, tool) => {
            if (!TOOLS[harness][tool]) {
                throw new Error(`prompts/${name}.md: unknown placeholder ${m}`);
            }
            return TOOLS[harness][tool];
        });
}

/** Rewrites every `<!-- prompt: name [harness] [fenced] -->` … `<!-- /prompt -->` region of a Markdown file. */
function fillMarkers(file, text) {
    return text.replace(/(<!-- prompt: ([\w-]+)((?: [\w-]+)*) -->\n)[\s\S]*?(<!-- \/prompt -->)/g, (_m, open, name, opts, close) => {
        const flags = opts.trim().split(/\s+/).filter(Boolean);
        const harness = flags.find(f => TOOLS[f]) ?? 'mcp';
        const body = render(name, harness);
        return open + (flags.includes('fenced') ? '```text\n' + body + '\n```' : body) + '\n' + close;
    });
}

const outputs = new Map();
const files = execFileSync('git', ['ls-files', '*.md', '*.txt'], { cwd: root, encoding: 'utf8' }).split('\n').filter(Boolean);
for (const file of files.filter(f => !f.startsWith('prompts/'))) {
    const text = readFileSync(join(root, file), 'utf8');
    if (text.includes('<!-- prompt: ')) {
        outputs.set(file, fillMarkers(file, text));
    }
}
{
    const text = readFileSync(join(root, RS_OUT), 'utf8');
    const begin = text.indexOf(RS_BEGIN);
    const end = text.indexOf(RS_END);
    if (begin < 0 || end < begin) {
        throw new Error(`${RS_OUT}: the marker lines of the generated region are missing`);
    }
    outputs.set(RS_OUT, text.slice(0, begin) + rustRegion() + text.slice(end));
}

const stale = [];
for (const [file, next] of outputs) {
    let current = '';
    try {
        current = readFileSync(join(root, file), 'utf8');
    } catch { /* new file */ }
    if (current !== next) {
        stale.push(file);
        if (!check) {
            writeFileSync(join(root, file), next);
        }
    }
}
if (check && stale.length) {
    console.error(`Out of date with prompts/ (run \`make prompts\`):\n  ${stale.join('\n  ')}`);
    process.exit(1);
}
console.log(check ? `prompts: ${outputs.size} files up to date` : stale.length ? `prompts: updated ${stale.join(', ')}` : 'prompts: up to date');
